import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
import {convert,findOffice} from '../electron/conversion';
import {createHash} from 'node:crypto';

test('bundled runtime converts real documents without a system Office installation',{timeout:300000},async()=>{
  const bundled=path.resolve('vendor/libreoffice');
  const engine=await findOffice(bundled);
  assert.equal(engine,path.join(bundled,'program','soffice.com'),'Bundled runtime must be present and preferred');
  const dir=path.resolve('.cache/engine-smoke',String(Date.now()));await mkdir(dir,{recursive:true});
  const input=path.join(dir,'Tài liệu gốc.txt');
  const text='Warp kiểm tra chuyển đổi.\nTài liệu gốc được giữ nguyên.\n';
  await writeFile(input,text,'utf8');
  const before=createHash('sha256').update(await readFile(input)).digest('hex');
  const docx=await convert(input,'docx',engine!);
  assert.equal((await readFile(docx)).subarray(0,2).toString(),'PK');
  const pdf=await convert(docx,'pdf',engine!);
  const pdfBytes=await readFile(pdf);assert.equal(pdfBytes.subarray(0,5).toString(),'%PDF-');
  assert.ok(/\/Type\s*\/Page\b/.test(pdfBytes.toString('latin1')));
  const back=await convert(docx,'txt',engine!);
  assert.notEqual(back,input);assert.ok((await readFile(back,'utf8')).includes('kiểm tra chuyển đổi'));
  assert.equal(createHash('sha256').update(await readFile(input)).digest('hex'),before);
  const csv=path.join(dir,'Bảng số liệu.csv');await writeFile(csv,'Product,Quantity\nPen,3\nBook,2\n','utf8');
  const xlsx=await convert(csv,'xlsx',engine!);
  assert.equal((await readFile(xlsx)).subarray(0,2).toString(),'PK');
  const sheetPdf=await convert(xlsx,'pdf',engine!);
  assert.equal((await readFile(sheetPdf)).subarray(0,5).toString(),'%PDF-');
  const repeated=await convert(docx,'pdf',engine!);assert.notEqual(repeated,pdf);
  assert.deepEqual(await readFile(pdf),pdfBytes,'Existing PDF must be preserved');
  await writeFile(path.resolve('.cache/engine-check.json'),JSON.stringify({passed:true,engine,outputDirectory:dir,checks:['TXT to DOCX','DOCX to PDF','Unicode text roundtrip','CSV to XLSX','XLSX to PDF','original SHA256 unchanged','duplicate output preserved']},null,2));
});
